function normalizeRawSize(rawSize) {
  if (!rawSize) return null;

  let s = rawSize.toString().trim().toUpperCase();

  // ---------- ONE SIZE ----------
  if (
    s === "ONE SIZE" ||
    s === "ONESIZE" ||
    s === "OS" ||
    s === "FREE"
  ) {
    return "ONE SIZE";
  }

  // ---------- REMOVE WORDS ----------
  s = s
    .replace(/SIZE/gi, "")
    .replace(/EU/gi, "")
    .replace(/\(.*?\)/g, "")
    .trim();

  // ---------- LETTER SIZES ----------
  if (["XXS", "XS", "S", "M", "L", "XL", "XXL"].includes(s)) {
    return s;
  }

  // ---------- NUMERIC (36, 36.5, 7, 8.5 etc) ----------
  if (/^\d+(\.\d+)?$/.test(s)) {
    return s;
  }

  // ---------- MM SIZES (220mm, 235MM) ----------
  if (/^\d{3}MM$/i.test(s)) {
    return s.replace("MM", "");
  }

  // ---------- BELT / CM (85, 90 etc) ----------
  if (/^\d{2,3}CM$/i.test(s)) {
    return s.replace("CM", "");
  }

  return null;
}

function mapSizeFromTrenbe(rawSize, productType) {
  const normalized = normalizeRawSize(rawSize);
  if (!normalized) return null;

  // ONE SIZE valid everywhere
  if (normalized === "ONE SIZE") {
    return "ONE SIZE";
  }

  // Shoes
  if (["BOOTS", "FLATS", "HEELS", "LOAFERS", "SANDALS", "SNEAKERS", "WEDGES"].includes(productType)) {
    return ALLOWED_SHOE_SIZES.has(normalized) ? normalized : null;
  }

  // Clothing
  if ([
    "COATS", "DRESSES", "JACKETS", "JEANS", "JUMPSUITS", "KNITWEAR",
    "PANTS", "ROMPERS", "SETS", "SHIRTS", "SHORTS", "SKIRTS", "TOPS"
  ].includes(productType)) {
    return ALLOWED_CLOTHING_SIZES.has(normalized) ? normalized : null;
  }

  return null;
}



