  function getFinalPriceUSDToSGDWithMargin(priceUSD) {
    if (!priceUSD) return "";

    // Convert USD to SGD using env rate
    const sgdCost = priceUSD * USD_TO_SGD_RATE;

    // const sgdCost = Math.ceil((priceUSD * USD_TO_SGD_RATE) / 5) * 5;

    let multiplier;
    if (sgdCost <= 500) multiplier = 1.4;
    else if (sgdCost <= 1000) multiplier = 1.35;
    else if (sgdCost <= 2500) multiplier = 1.3;
    else if (sgdCost <= 5000) multiplier = 1.25;
    else if (sgdCost <= 10000) multiplier = 1.2;
    else multiplier = 1.15;

    const finalPrice = Math.ceil((sgdCost * multiplier) / 5) * 5;
    // console.log(finalPrice)
    return finalPrice;
  }

