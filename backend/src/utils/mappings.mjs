  function mapMaterialDetail(rawValue) {
    if (!rawValue) return 'Others';

    // Normalize input
    const normalized = rawValue
      .trim()
      .toLowerCase()
      .replace(/[-,/]/g, " ") // replace separators
      .replace(/\s+/g, " "); // multiple spaces to single

    // Loop through map keys and fuzzy match
    for (const key of Object.keys(MATERIALDTAIL_MAP)) {
      const normalizedKey = key
        .trim()
        .toLowerCase()
        .replace(/[-,/]/g, " ")
        .replace(/\s+/g, " ");

      // Fuzzy Matching
      if (normalized.includes(normalizedKey)) {
        return MATERIALDTAIL_MAP[key];
      }
    }

    return "Others"; // fallback
  }

  // // Title Cleaner
  function advancedCleanTitle(title, options = {}) {
    const {
      removeSizes = true,
      removeProductCodes = true,
      removeCommonWords = false,
      minWordLength = 2,
    } = options;

    if (!title || typeof title !== "string") return "";

    let words = title.split(" ").filter((word) => {
      const trimmedWord = word.trim();
      if (!trimmedWord) return false;

      //  Remove pure numeric tokens (example: 120500396)
      if (/^\d+$/.test(trimmedWord)) return false;

      //  Remove size-like numeric values (10, 12.5)
      if (removeSizes && /^\d{1,2}(\.\d{1,2})?$/.test(trimmedWord))
        return false;

      //  Remove model / product codes (letters + numbers mixed)
      //    Example: S0105CVXS, WW2B0J70ZXL, 8BS010, AS1160, etc.
      if (
        removeProductCodes &&
        /[A-Za-z]/.test(trimmedWord) &&
        /\d/.test(trimmedWord)
      ) {
        return false;
      }

      //  Must contain at least letters
      return new RegExp(`[A-Za-z]{${minWordLength},}`).test(trimmedWord);
    });

    let result = words.join(" ").trim().replace(/\s+/g, " ");

    // Optional remove common category words
    if (removeCommonWords) {
      const commonWords = [
        "Size",
        "Medium",
        "Small",
        "Large",
        "Mini",
        "Tote",
        "Shoulder",
        "Bag",
        "Crossbody",
        "Clutch",
        "Sneakers",
        "Wallet",
        "Pouch",
        "Chain",
        "Leather",
      ];
      const pattern = new RegExp(`\\b(${commonWords.join("|")})\\b`, "gi");
      result = result.replace(pattern, "").replace(/\s+/g, " ").trim();
    }

    return result;
  }


  function cleanDescription(html) {
    if (!html) return null;

    let text = html
      .replace(/<br\s*\/?>/gi, "\n")
      .replace(/<\/div>/gi, "\n")
      .replace(/<[^>]+>/g, "")
      .replace(/\n{2,}/g, "\n")
      .trim();

    //  Remove "trenbe Code: XXXXX"
    text = text.replace(/trenbe\s*code:\s*\d+/gi, "");

    //  Remove SKU style numeric codes (8–12 digit numbers) often used by Trenbe
    text = text.replace(/\b\d{8,12}\b/g, "");

    //  Remove leftover double spaces & trim again
    return text.replace(/\n{2,}/g, "\n").trim();
  }

